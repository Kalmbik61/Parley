const translators = { en: createTranslator('en', sessionPilotCatalog), ru: createTranslator('ru', sessionPilotCatalog) };

export const pilotText: Translator<typeof sessionPilotCatalog.en> = (key, ...args) => translators[appI18n.locale](key, ...args);

export function sessionCountText(count: number): string {
  const plural = appI18n.pluralCategory(count);
  const form = plural === 'one' || plural === 'few' || plural === 'many' ? plural : 'other';
  return pilotText(`sidebar.sessionCount.${form}`, { count: appI18n.formatNumber(count) });
}
