/**
 * Предел вложенности цитат Markdown (Parley 0.3.0). Сотни вложенных `>` разбор и отрисовка переваривают секундами,
 * тысячи — переполняют стек. Такой текст пишет только сломанный или злонамеренный агент, поэтому глубже предела
 * его не разбирают как Markdown: лента и почта показывают его сырым (`components/MarkdownBoundary.tsx`), выдержка
 * цитаты берёт сырую строку (`rooms/excerpt.ts`), а поиск `@human` упоминания в нём не видит
 * (`rooms/room-remark.ts#hasHumanMention`) — как и лента, где чипа в сыром тексте нет.
 */

/** Глубже стольких вложенных цитат текст не Markdown; живая переписка до такой глубины не доходит. */
export const QUOTE_DEPTH_MAX = 100;

/** Строка, которая начинается больше чем с `QUOTE_DEPTH_MAX` знаков `>` (между ними — пробелы и табы). */
const TOO_DEEP = new RegExp(`^(?:[ \\t]*>){${QUOTE_DEPTH_MAX + 1}}`, 'm');

/** В тексте есть строка с цитатами глубже предела. */
export function markdownTooDeep(text: string): boolean {
  return TOO_DEEP.test(text);
}
