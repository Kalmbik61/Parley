import type { WorkMap } from './types.js';

/**
 * Короткая системная вставка, которую харнесс отдаёт агенту при каждом запуске
 * (`--append-system-prompt`). Она первый из двух слоёв гида: дешёвая, не больше
 * двенадцати строк, и рассказывает ровно то, без чего агент не поймёт, где он и
 * чем ему пользоваться. Подробности — второй слой, инструмент `read_guide`.
 *
 * Системный промпт в транскрипте не хранится: он собирается заново и при
 * `--resume`, поэтому текст зависит только от карты и id сессии.
 */

/**
 * Заголовок и цель работы пишет человек — там бывают переносы строк, а счёт
 * строк вставки от них поехал бы.
 */
const oneLine = (text: string): string => text.replace(/\s+/g, ' ').trim();

/** Системная вставка для сессии `sessionId` работы `map`. */
export function systemGuidance(map: WorkMap, sessionId: string): string {
  const lines = [
    `Ты в харнессе my-harnas: работа ${map.work.id} — ${oneLine(map.work.title)}, твоя сессия ${sessionId}; координация идёт через инструменты MCP-сервера harnas.`,
  ];

  const goal = oneLine(map.work.goal);
  if (goal !== '') lines.push(`Цель работы: ${goal}`);

  lines.push(
    'get_map — карта работы: сессии, их статусы, резюме, артефакты, сообщения и провайдеры; вызови первым делом.',
    'report — твой отчёт: done или failed в конце, progress по ходу дела.',
    'spawn_session — новая сессия в этой же работе; её запустит пользователь.',
    'wait_for — ждать завершения сессии работы или входящего сообщения.',
    'send_message — письмо другой сессии работы: question — жду ответа, decision — договорились, note — заметка (по умолчанию).',
    'check_inbox — письма коллег приходят сами как <channel source="harnas">; отвечай send_message только на question; check_inbox — страховка.',
    'read_guide — подробный гид по харнессу: сущности, жизненный цикл, что куда класть.',
    'Подзадачу этой темы, которая живёт дольше одного хода или должна идти параллельно, отдавай в spawn_session этой же работы; собственные субагенты — для коротких разведок и правок.',
    'Перед завершением обязательно вызови report — иначе результат никуда не попадёт.',
  );
  return lines.join('\n');
}
