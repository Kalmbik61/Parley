export const GUIDE = `# Харнесс my-harnas: как им пользоваться

## Что здесь есть

Работа — тема целиком: заголовок, цель, набор сессий и переписка между ними.
Сессия — один запуск агента внутри работы: у неё есть ярлык (роль), задача,
статус, резюме и артефакты. Карта работы (\`map.json\`) — общая память: её
пишет харнесс, читают все. Всё, что ты хочешь передать соседям и человеку,
попадает туда через инструменты, а не через файлы наугад.

Сессии образуют дерево: у порождённой записан родитель, а \`contextFrom\` —
список сессий, чьи резюме и артефакты попали в её бриф.

## Жизненный цикл сессии

- \`pending\` — запись есть, процесс ещё не поднят; запускает её человек.
- \`active\` — процесс работает.
- \`exited\` — процесс вышел, отчёта не было.
- \`done\` / \`failed\` — итог из твоего \`report\`; только он и ставит их.

Отчёт важнее выхода процесса: сессия, успевшая отчитаться, остаётся в своём
\`done\` или \`failed\`.

## Инструменты

\`get_map\` — карта целиком плюс список провайдеров реестра с пометкой, есть ли
команда в PATH. Вызывай первым делом: id сессий и их статусы берутся отсюда.

\`report(status, summary, artifacts)\` — \`done\` или \`failed\` в конце,
\`progress\` по ходу дела (статус не меняется, резюме перезаписывается).
Резюме — две-три фразы по существу: его прочитают соседние сессии в своём
брифе и человек в панели. Артефакты — файлы результата, путь всегда
относительно корня проекта; содержимое в карту не копируется, только путь и
вид («план», «отчёт», «патч»).

\`spawn_session(provider, label, task, contextFrom, agent)\` — новая сессия в
этой же работе. Заводится запись \`pending\` и пишется бриф; процесс поднимет
человек. Предпочитай \`spawn_session\` своим субагентам, когда подзадача этой
темы живёт дольше одного хода, должна идти параллельно с твоей или её результат
нужен кому-то ещё: такая сессия видна в панели, у неё свой отчёт и своя
история. Короткая разведка или локальная правка — дешевле собственным
субагентом.

\`agent\` необязателен и задаёт роль сессии: это имя определения агента Claude
Code — файла \`.claude/agents/<name>.md\` проекта или \`~/.claude/agents/<name>.md\`.
Имени без такого файла харнесс не примет, и провайдеру, который ролей не
принимает, поле не передать.

\`wait_for(target, timeoutSec)\` — ждать сессию по её id или входящее письмо
(\`target: "inbox"\`). По таймауту приходит \`{"state":"running"}\` — решай сам,
звать ли снова. Ответ \`state: deleted\` значит, что сессию удалил человек:
ждать больше нечего, перепланируй работу без неё. Неизвестный id — ошибка
сразу, это опечатка.

\`send_message(to, text, kind)\` и \`check_inbox()\` — переписка внутри работы.
Письмо живёт в карте, пока адресат не заберёт его; этикет и виды писем — ниже,
в «Как разговаривать».

## Бриф

Стартовый промпт порождённой сессии собирает харнесс: работа и её цель, ярлык
и задача сессии, резюме и артефакты сессий из \`contextFrom\`, правила. Файл
лежит в \`briefs/<id>.md\` и правится руками до запуска. Пиши задачу так, чтобы
её хватило без твоего контекста: читать твой транскрипт новая сессия не может.

## Как разговаривать

Тред — переписка твоей группы: родитель, братья, ты и твои потомки. Коллег
этой группы и её решения ты уже видел в брифе, человек видит ленту писем в
панели. Письма коллег приходят сами, тегом \`<channel source="harnas">\`;
\`check_inbox\` — страховка на случай, если канал молчит.

Три вида письма:

- \`question\` — жду ответа. Отвечай тому, кто спросил, в том же ходу, коротко
  и по делу, и не заканчивай ход с неотвеченным вопросом.
- \`decision\` — договорились. Фиксируй договорённость одним письмом
  \`kind: decision\` тому, с кем договорился: решения треда собираются из таких
  писем сами и попадают в бриф следующей сессии.
- \`note\` — всё остальное: заметка по ходу дела.

На \`note\` и \`decision\` не отвечай: «спасибо» и «принято» стоят коллеге
целого хода. И не жди \`wait_for\` того, кто и так ответит письмом, — письмо
разбудит тебя само.

У переписки есть потолок: \`messageRate\` писем от одной сессии за скользящий
час (по умолчанию 20). Упёрся в него — разговор пошёл по кругу: не переотправляй
то же письмо, а отчитайся \`report\` и скажи человеку, на чём вы застряли.

Если сессию запустили ролью-агентом Claude Code, её определение с урезанным
списком \`tools\` обязано включать \`mcp__harnas__*\`: иначе роль не сможет ни
написать коллеге, ни отчитаться, а харнесс этого не проверяет — файл агента он
не читает.

## Чего не делать

- Не заканчивать без \`report\` — результат никуда не попадёт.
- Не писать в \`map.json\`, \`briefs/\` и \`events/\` руками: карту пишет харнесс.
- Не удалять и не переносить каталоги \`.harnas\` через shell, даже если тебя
  просят «убрать работу»: инструмента удаления у тебя нет намеренно. Сессию
  удаляет человек из TUI (\`prefix d\`), работу — тоже из TUI; скажи ему об этом.
- Не звать \`spawn_session\` ради того, что делается за один ход.
- Не ждать \`wait_for\` сессию, которую никто не запустит: \`pending\` поднимает
  человек, скажи ему об этом.
`;
