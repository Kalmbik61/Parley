export type ReceiptKind = keyof typeof receipts.en;

function makeTelegramTexts(locale: AppLocale) {
  const t = createTranslator(locale, texts);
  const receipt = createTranslator(locale, receipts);
  const commandText = createTranslator(locale, commands);
  const number = createI18n(locale).formatNumber;
  return {
    linked: (macName: string) => t('linked', { macName }),
    help: t('help'),
    commands: (['status', 'new', 'help'] as const).map((command) => ({
      command,
      description: commandText(command),
    })),
    assistantOff: t('assistantOff'),
    voiceOff: t('voiceOff'),
    voiceTooLong: t('voiceTooLong'),
    voiceFailed: t('voiceFailed'),
    tooLong: t('tooLong'),
    noLongerCurrent: t('noLongerCurrent'),
    notReadyYet: t('notReadyYet'),
    couldNot: (reason: string) => t('couldNot', { reason }),
    newConversation: t('newConversation'),
    answeredAtMac: t('answeredAtMac'),
    expired: t('expired'),
    returnNotePrompt: (lead: string) => t('returnNotePrompt', { lead }),
    otherPrompt: t('otherPrompt'),
    sentAsAnswer: (session: string) => t('sentAsAnswer', { session }),
    sentAsNote: (lead: string) => t('sentAsNote', { lead }),
    waitCancelled: t('waitCancelled'),
    unlinked: t('unlinked'),
    restarted: t('restarted'),
    reminderOff: (id: string, what: string) => t('reminderOff', { id, what }),
    sentTo: (name: string) => t('sentTo', { name }),
    heard: (text: string) => t('heard', { text }),
    needsYou: (name: string, where: string) => t('needsYou', { name, where }),
    finished: (name: string, where: string) => t('finished', { name, where }),
    letter: (from: string, where: string) => t('letter', { from, where }),
    waitingAtMac: (name: string) => t('waitingAtMac', { name }),
    revised: t('revised'),
    cardTitle: (name: string, where: string) => t('cardTitle', { name, where }),
    expiresWithTurn: t('expiresWithTurn'),
    receipt: (kind: ReceiptKind, time: string) => t('receipt', { result: receipt(kind), time }),
    permissionTitle: (tool: string) => t('permissionTitle', { tool }),
    questionTitle: t('questionTitle'),
    questionOf: (index: number, total: number) =>
      t('questionOf', { index: number(index), total: number(total) }),
    planTitle: t('planTitle'),
    decisionTitle: t('decisionTitle'),
    completionTitle: t('completionTitle'),
    assistantTo: (target: string, where: string) => t('assistantTo', { target, where }),
    assistantNewRoom: (where: string) => t('assistantNewRoom', { where }),
    assistantPlan: (where: string) => t('assistantPlan', { where }),
    closesForGood: t('closesForGood'),
    assistantRoomLine: (title: string, members: string, lead: string) =>
      t('assistantRoomLine', { title, members, lead }),
    assistantNote: (text: string) => t('assistantNote', { text }),
    assistantAnswerLine: (question: string, answer: string) =>
      t('assistantAnswerLine', { question, answer }),
    assistantAcceptDecision: (room: string) => t('assistantAcceptDecision', { room }),
    assistantReturnDecision: (lead: string) => t('assistantReturnDecision', { lead }),
    assistantAskTitle: (verb: string, name: string) => t('assistantAskTitle', { verb, name }),
    assistantPlanTitle: (verb: string, name: string) => t('assistantPlanTitle', { verb, name }),
    consentHeader: t('consentHeader'),
    consentTitle: t('consentTitle'),
    switchTitle: t('switchTitle'),
    switchAsks: (card: { ref: { sessionId: string }; providerLabel: string; model: string | null; reason: string; requestedBy: { sessionId: string } }) => t('switchAsks', {
      who: '@' + card.requestedBy.sessionId.replace('-', ''),
      session: '@' + card.ref.sessionId.replace('-', ''),
      provider: card.providerLabel + (card.model === null ? '' : ` (${card.model})`),
      reason: card.reason + (/[.!?]$/.test(card.reason) ? '' : '.'),
    }),
    switchAllowed: t('switchAllowed'),
    consentRequestedBy: (label: string, project: string) =>
      t('consentRequestedBy', { label, project }),
    trusted: t('trusted'),
    denied: t('denied'),
  };
}

export function telegramButtons(locale: AppLocale) {
  const t = createTranslator(locale, buttons);
  return { ...buttons[locale], doAll: (count: number) => t('doAll', { count }) };
}

const telegram = { en: makeTelegramTexts('en'), ru: makeTelegramTexts('ru') };
export const telegramTexts = (locale: AppLocale) => telegram[locale];
export const T = telegram.en;
