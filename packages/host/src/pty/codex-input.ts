/**
 * Ввод в TUI Codex (спека комнат Organic, 3.6, «Ввод»; исследование Codex, раздел 5). Письма и указатели
 * харнесса уходят в поле ввода агента, и поле у Codex не простое:
 * - bracketed paste включён: текст идёт вставкой `ESC[200~ … ESC[201~`, иначе быстрый поток знаков
 *   Codex считает «не вставкой» и Enter внутри него отправляет сообщение раньше времени;
 * - между вставкой и клавишей — короткая пауза (десятки миллисекунд), чтобы TUI принял вставку;
 * - Enter занятому агенту — вмешательство в идущий ход (steer), Tab — очередь на следующий ход. Письма
 *   харнесса в ход не вмешиваются: агент работает — Tab, у приглашения — Enter;
 * - всплывающие меню (`/` команды, `@` файлы, `$` скиллы) забирают Enter: текст, кончающийся таким
 *   токеном, Enter не отправил бы, а начинающийся с `/`, `!` или `$` Codex прочитал бы как команду,
 *   оболочку или скилл.
 * Настоящий Codex не запускался: задержки, поведение Tab у приглашения и разбор токенов на живом не
 * сверены (исследование, раздел 14).
 */

export const PASTE_START = '\x1b[200~';
export const PASTE_END = '\x1b[201~';

/** Клавиша отправки у приглашения и клавиша очереди у занятого агента (`chat_composer.rs`, раскладка по умолчанию). */
export const KEY_ENTER = '\r';
export const KEY_TAB = '\t';

/**
 * Пауза между вставкой и клавишей отправки у Codex, мс: десятки, а не полсекунды будильника. Полсекунды
 * будильника — окно, в котором человек мог начать печатать своё; Codex достаточно принять вставку.
 */
export const CODEX_SUBMIT_DELAY_MS = 60;

/**
 * Что вставка меняет смысл первой строки: `/` — слэш-команда, `!` — режим оболочки, `$` — скилл. Ведущие
 * пробелы Codex может обрезать до разбора, поэтому смотрим за ними.
 */
const LEADING_SPECIAL = /^\s*[/!$]/;

/**
 * Токен на конце текста, под которым Codex открывает меню: `@файл`, `$скилл`, `/путь`. Токен — всё от
 * последнего пробела до конца, и точка в него входит (`@файл.` — всё ещё токен); завершает его пробел.
 */
const TRAILING_MENU_TOKEN = /(?:^|\s)[@$/]\S*$/;

/**
 * Текст, безопасный для поля ввода Codex. Начало на `/`, `!`, `$` получает видимый префикс `- ` — не
 * пробел, который Codex мог бы обрезать и всё равно прочитать команду; конец токеном меню закрывается
 * пробелом. Остальной текст не меняется.
 */
export function sanitizeForCodex(text: string): string {
  let safe = text;
  if (LEADING_SPECIAL.test(safe)) safe = `- ${safe.trimStart()}`;
  if (TRAILING_MENU_TOKEN.test(safe)) safe = `${safe} `;
  return safe;
}

/** Вставка для Codex: очищенный текст в маркерах bracketed paste. */
export const codexPaste = (text: string): string =>
  `${PASTE_START}${sanitizeForCodex(text)}${PASTE_END}`;

/**
 * Клавиша отправки по состоянию агента в момент нажатия: работает — Tab (очередь), иначе Enter. Решается
 * на самой отправке, а не при вставке: за паузу ход мог закончиться (Tab у приглашения ничего не даёт) или
 * начаться (Enter вмешался бы в него).
 */
export const codexSubmitKey = (activity: string | undefined): string =>
  activity === 'working' ? KEY_TAB : KEY_ENTER;
