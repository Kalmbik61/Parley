type HostTranslator = ReturnType<typeof createTranslator<typeof catalog.en>>;
const en: HostTranslator = createTranslator('en', catalog);
const ru = createTranslator('ru', catalog);

export interface HostText {
  english: string;
  in(locale?: AppLocale): string;
}

/** Помечает собственный текст Parley. Переданные причины и внешняя диагностика остаются строками. */
export function hostText<Key extends keyof typeof catalog.en>(
  ...message: Parameters<typeof en<Key>>
): HostText {
  const english = en<Key>(...message);
  return { english, in: (locale) => (locale === 'ru' ? ru<Key>(...message) : english) };
}
